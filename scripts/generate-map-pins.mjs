// Regenerate bundled native map icons with ImageMagick (no runtime dependency).
import { mkdirSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../artifacts/nearbuy/", import.meta.url));
const output = `${root}assets/map-pins`;
mkdirSync(output, { recursive: true });
const glyphs = [..."ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789", "?"];
const palettes = { shop: "#E77712", service: "#7844D8" };
const entries = [];
for (const glyph of glyphs) {
  const key = glyph === "?" ? "fallback" : glyph;
  for (const [kind, color] of Object.entries(palettes)) {
    for (const scale of [1, 2, 3]) {
      const suffix = scale === 1 ? "" : `@${scale}x`;
      // Draw at 4x then downsample: sharp outlines and letters at each density.
      execFileSync("magick", [
        "-size", "224x272", "xc:none",
        "-fill", "#17243B30", "-draw", "ellipse 112,251 33,8 0,360",
        "-fill", color, "-stroke", "white", "-strokewidth", "12",
        "-draw", "path 'M 112,249 L 48,165 C -7,107 28,18 112,18 C 196,18 231,107 176,165 Z'",
        "-stroke", "none", "-fill", "#FFFFFF28",
        "-draw", "ellipse 94,69 45,27 0,360",
        "-font", "DejaVu-Sans-Bold", "-pointsize", "108",
        "-fill", "white", "-gravity", "North", "-annotate", "+0+44", glyph,
        "-resize", `${56 * scale}x${68 * scale}`,
        "-depth", "8", "-strip",
        `${output}/${kind}-${key}${suffix}.png`,
      ]);
    }
  }
  entries.push(`  "${glyph}": { shop: require("../assets/map-pins/shop-${key}.png"), service: require("../assets/map-pins/service-${key}.png") },`);
}
writeFileSync(`${root}lib/map-pin-images.ts`, `// Generated by scripts/generate-map-pins.mjs. Do not edit the asset table manually.
import type { ImageSourcePropType } from "react-native";

const pins: Record<string, { shop: ImageSourcePropType; service: ImageSourcePropType }> = {
${entries.join("\n")}
};

export function getMapPinImage(name: string, isService: boolean): ImageSourcePropType {
  const initial = Array.from(name.trim().normalize("NFD").replace(/[\\u0300-\\u036f]/g, "").toUpperCase())[0] ?? "?";
  const pin = pins[initial] ?? pins["?"];
  return isService ? pin.service : pin.shop;
}
`);
